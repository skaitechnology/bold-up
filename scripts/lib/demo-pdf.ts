// Builds a tiny, valid one-page PDF for seeded demo documents.
// The page says in large letters that the document is fictional and has no value.

export function demoPdf(title: string, holder: string): Buffer {
  const escape = (text: string) => text.replace(/[\\()]/g, "\\$&").replace(/[^\x20-\x7e]/g, "?");
  const lines = [
    { size: 22, y: 760, text: "DOCUMENT DE DEMONSTRATION" },
    { size: 14, y: 732, text: "SANS VALEUR - FICTIONAL DEMO DOCUMENT, NO VALUE" },
    { size: 13, y: 680, text: `Type : ${title}` },
    { size: 13, y: 658, text: `Titulaire fictif : ${holder}` },
    { size: 11, y: 610, text: "Ce fichier a ete genere par le script de demonstration Bold Up." },
    { size: 11, y: 594, text: "Il ne represente aucun document officiel, diplome, carte ou attestation." },
    { size: 11, y: 562, text: "This file was generated by the Bold Up seed script. It is not an official document." },
  ];
  const stream = lines.map((line) => `BT /F1 ${line.size} Tf 60 ${line.y} Td (${escape(line.text)}) Tj ET`).join("\n");

  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>",
    `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`,
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
  ];

  let body = "%PDF-1.4\n";
  const offsets: number[] = [];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(body));
    body += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const xrefStart = Buffer.byteLength(body);
  body += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  body += offsets.map((offset) => `${String(offset).padStart(10, "0")} 00000 n \n`).join("");
  body += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;
  return Buffer.from(body, "latin1");
}
